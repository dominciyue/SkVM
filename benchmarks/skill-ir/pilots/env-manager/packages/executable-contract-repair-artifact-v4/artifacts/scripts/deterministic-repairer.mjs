var repairContract = ExecutableRepairContractSchema.parse(JSON.parse(await readFile2(resolve3(workDir, ".skvm-artifact/executable-repair-contract.json"), "utf8")));
var report = await repairEnvManagerArtifactsDeterministically({ workDir, repairContract });
