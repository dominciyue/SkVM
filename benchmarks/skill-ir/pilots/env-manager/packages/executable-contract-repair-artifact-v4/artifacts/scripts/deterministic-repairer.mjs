async function protectedTreeDigest(root, generated) {
  const entries = [];
  async function visit(directory) {
    const children = await readdir(directory, { withFileTypes: true });
    children.sort((left, right) => left.name.localeCompare(right.name));
    for (const child of children) {
      const path = resolve2(directory, child.name);
      const relativePath = portableRelative(root, path);
      const stat = await lstat(path);
      if (stat.isSymbolicLink()) {
        throw new Error(`deterministic repair rejects symbolic link: ${relativePath}`);
      }
      if (stat.isDirectory()) {
        await visit(path);
        continue;
      }
      if (!stat.isFile()) {
        throw new Error(`deterministic repair rejects unsupported entry: ${relativePath}`);
      }
      if (stat.nlink > 1) {
        throw new Error(`deterministic repair rejects hard link: ${relativePath}`);
      }
      if (generated.has(relativePath))
        continue;
      entries.push({ relativePath, sha256: sha256Bytes(await readFile(path)) });
    }
  }
  await visit(root);
  entries.sort((left, right) => left.relativePath.localeCompare(right.relativePath));
  const manifest = entries.map((entry) => `${entry.relativePath}\x00${entry.sha256}\x00`).join("");
  return sha256Bytes(Buffer.from(manifest, "utf8"));
}
async function readJson(path) {
  try {
    return JSON.parse(await readFile(path, "utf8"));
  } catch {
    return;
  }
}
function sameJson(left, right) {
  return JSON.stringify(left) === JSON.stringify(right);
}
function canonicalJson(value) {
  return `${JSON.stringify(value, null, 2)}
`;
}
function confirmedRules(variable) {
  const rules = new Map;
  for (const rule of variable.rules) {
    if (rule.disposition === "confirmed")
      rules.set(rule.field, rule.value);
  }
  return rules;
}
var RULE_FIELD_ORDER = [
  "type",
  "required",
  "minimum",
  "maximum",
  "format",
  "minLength",
  "sensitive"
];
function lowerSchemaRules(runtimeContract, repairContract) {
  const defaultStringEvidence = new Set(repairContract.schemaRulePolicy.defaultStringEvidenceKinds);
  const variables = {};
  for (const variable of [...runtimeContract.variables].sort((left, right) => left.name.localeCompare(right.name))) {
    const lowered = new Map;
    const confirmed = confirmedRules(variable);
    for (const [field, value] of confirmed)
      lowered.set(field, value);
    const evidenceKinds = [...variable.definitions, ...variable.references].map((ref) => ref.evidenceKind);
    const hasStringEvidence = evidenceKinds.some((kind) => defaultStringEvidence.has(kind));
    if (!confirmed.has("type") && hasStringEvidence)
      lowered.set("type", "string");
    const type = lowered.get("type");
    if (hasStringEvidence && (type === undefined || type === "string") && repairContract.schemaRulePolicy.uriNameSuffixes.some((suffix) => variable.name.endsWith(suffix))) {
      lowered.set("type", "string");
      lowered.set("format", "uri");
    }
    const hasServerReference = variable.references.some((reference) => reference.evidenceKind === "environment-reference");
    const hasClientReference = variable.references.some((reference) => reference.evidenceKind === "client-environment-reference");
    if (hasServerReference && !hasClientReference && repairContract.schemaRulePolicy.learnedRules.some((rule) => rule.kind === "server-sensitive-suffix" && variable.name.endsWith(rule.nameSuffix))) {
      lowered.set("sensitive", true);
    }
    const sensitive = confirmed.get("sensitive") === true;
    if (sensitive) {
      for (const rule of repairContract.schemaRulePolicy.learnedRules) {
        if (rule.kind === "sensitive-minimum-length-suffix" && variable.name.endsWith(rule.nameSuffix)) {
          lowered.set("type", "string");
          lowered.set("minLength", rule.minimum);
        }
      }
    }
    const ordered = {};
    for (const field of RULE_FIELD_ORDER) {
      if (lowered.has(field))
        ordered[field] = lowered.get(field);
    }
    variables[variable.name] = ordered;
  }
  return { variables };
}
function deriveEnvManagerDeterministicArtifacts(runtimeContractInput, repairContractInput) {
  const runtimeContract = PublicRuntimeContractSchema.parse(runtimeContractInput);
  const repairContract = ExecutableRepairContractSchema.parse(repairContractInput);
  const expectedNames = runtimeContract.variables.map((variable) => variable.name).sort((left, right) => left.localeCompare(right));
  return {
    report: derivePublicContractClassification(runtimeContract),
    exampleText: `${expectedNames.map((name) => `${name}=`).join(`
`)}
`,
    schema: lowerSchemaRules(runtimeContract, repairContract)
  };
}
async function atomicWrite(path, text) {
  const current = await lstat(path).catch(() => {
    return;
  });
  if (current?.isSymbolicLink()) {
    throw new Error(`deterministic repair rejects symbolic link: ${path}`);
  }
  if (current && (!current.isFile() || current.nlink > 1)) {
    throw new Error(`deterministic repair rejects hard link or unsupported output: ${path}`);
  }
  const temporary = resolve2(dirname(path), `.${path.split(/[\\/]/).at(-1)}.skvm-${crypto.randomUUID()}.tmp`);
  try {
    await writeFile(temporary, text, { encoding: "utf8", flag: "wx" });
    try {
      await rename(temporary, path);
    } catch (error) {
      const code = error.code;
      if (code !== "EEXIST" && code !== "EPERM")
        throw error;
      await rm(path, { force: true });
      await rename(temporary, path);
    }
  } finally {
    await rm(temporary, { force: true });
  }
}
async function repairEnvManagerArtifactsDeterministically(options) {
  const root = resolve2(options.workDir);
  const rootStat = await lstat(root).catch(() => {
    return;
  });
  if (!rootStat?.isDirectory() || rootStat.isSymbolicLink()) {
    throw new Error("deterministic repair workdir must be a regular directory");
  }
  const repairContract = ExecutableRepairContractSchema.parse(options.repairContract);
  const runtimeContractPath = resolve2(root, ".skvm-artifact", "public-runtime-contract.json");
  const runtimeContractBytes = await readFile(runtimeContractPath);
  if (sha256Bytes(runtimeContractBytes) !== repairContract.runtimeContractSha256) {
    throw new Error("runtime contract digest mismatch");
  }
  const runtimeContract = PublicRuntimeContractSchema.parse(JSON.parse(runtimeContractBytes.toString("utf8")));
  if (runtimeContract.taskContractDigest !== repairContract.taskContractDigest) {
    throw new Error("task contract digest mismatch between runtime evidence and repair contract");
  }
  const generated = new Set(runtimeContract.generatedOutputs);
  const contractOutputs = new Set(repairContract.outputs.map((output) => output.relativePath));
  if (generated.size !== contractOutputs.size || [...generated].some((path) => !contractOutputs.has(path))) {
    throw new Error("generated output registry mismatch");
  }
  const protectedDigestBefore = await protectedTreeDigest(root, generated);
  const operations = [];
  const desired = deriveEnvManagerDeterministicArtifacts(runtimeContract, repairContract);
  const desiredReport = desired.report;
  const reportPath = resolve2(root, "env-report.json");
  const currentReport = await readJson(reportPath);
  if (!sameJson(currentReport, desiredReport)) {
    await atomicWrite(reportPath, canonicalJson(desiredReport));
    operations.push({
      operation: "rewrite-canonical-report",
      relativePath: "env-report.json",
      jsonPointer: "/",
      contractRef: "derivations/public-classification/v3"
    });
  }
  const examplePath = resolve2(root, ".env.example");
  const exampleText = await readFile(examplePath, "utf8").catch(() => "");
  const desiredExample = desired.exampleText;
  if (exampleText !== desiredExample) {
    await atomicWrite(examplePath, desiredExample);
    operations.push({
      operation: "rewrite-redacted-example",
      relativePath: ".env.example",
      jsonPointer: "/",
      contractRef: "policies/redacted-dotenv/v1"
    });
  }
  const schemaPath = resolve2(root, ".env.schema.json");
  const currentSchema = await readJson(schemaPath);
  const desiredSchema = desired.schema;
  if (!sameJson(currentSchema, desiredSchema)) {
    await atomicWrite(schemaPath, canonicalJson(desiredSchema));
    operations.push({
      operation: "upsert-confirmed-schema-rules",
      relativePath: ".env.schema.json",
      jsonPointer: "/variables",
      contractRef: "policies/env-manager-development-repair-policy/v1"
    });
  }
  const protectedDigestAfter = await protectedTreeDigest(root, generated);
  return DeterministicRepairReportSchema.parse({
    schemaVersion: "deterministic-repair-report/v1",
    catalog: "executable-contract-repair-artifact/v4",
    status: operations.length > 0 ? "changed" : "no-change",
    operations,
    protectedDigestBefore,
    protectedDigestAfter
  });
}

